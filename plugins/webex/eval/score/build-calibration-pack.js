#!/usr/bin/env node
// ********* EVAL/SCORE/BUILD-CALIBRATION-PACK.JS *********
'use strict';

// Turns run bundles into the "real" sections of the calibration packs.
//
//   node plugins/webex/eval/score/build-calibration-pack.js <bundle-dir>...
//
// Writes plugins/webex/calibration/{task-fidelity,response-quality}.real.md,
// which are pasted into the packs. The perturbed sections stay hand-authored:
// their whole value is that a person chose exactly one thing to break.
//
// Only the *real* thirds are generated here, and deliberately without judge
// ratings — a grader who sees the model's answer first is anchored by it, and
// the blind labels are the entire point of the exercise.
//
// Matching reuses score-tasks.js rather than re-deriving pairs, so a grader
// judges exactly the pairing the scorer will later be measured against.

const fs = require('node:fs');
const path = require('node:path');

const { scoreTasks } = require('./score-tasks');
const { replyForQuestion } = require('./score-response');

const OUT_DIR = path.join(__dirname, '..', '..', 'calibration');

function loadBundle(target) {
  const stat = fs.statSync(target);
  const file = stat.isDirectory() ? path.join(target, 'bundle.json') : target;
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

// The transcript a grader reads, with the cited lines marked exactly as the
// judge sees them.
function renderConversation(messages, marked) {
  const cited = new Set(marked ?? []);
  return messages
    .map((m) => `${cited.has(m.number) ? '->' : '  '} [${m.number}] ${m.sender}: ${m.text}`)
    .join('\n');
}

function collect(bundleDirs) {
  const conversations = new Map(); // scenarioId -> messages
  const taskExamples = [];
  const responseExamples = [];

  for (const dir of bundleDirs) {
    const bundle = loadBundle(dir);
    const scenario = bundle.scenario ?? {};
    const scenarioId = scenario.id ?? 'unknown';
    const runId = (bundle.meta?.evalRunId ?? 'run').slice(0, 8);
    if (!conversations.has(scenarioId)) conversations.set(scenarioId, scenario.messages ?? []);

    for (const pair of scoreTasks(bundle).matched ?? []) {
      taskExamples.push({
        scenarioId,
        runId,
        cited: (pair.observedMessageIds ?? [])
          .map((id) => Number(String(id).split('-msg-')[1]))
          .filter(Number.isFinite),
        title: pair.observedTitle,
        description: pair.observedDescription,
        reference: pair.expectedTitle,
      });
    }

    for (const check of scenario.recallChecks ?? []) {
      const send = replyForQuestion(bundle.sends, check.questionMessageNumber);
      responseExamples.push({
        scenarioId,
        runId,
        questionNumber: check.questionMessageNumber,
        reply: send ? send.markdown : null,
        points: check.expectedAnswerPoints ?? [],
      });
    }
  }

  return { conversations, taskExamples, responseExamples };
}

function renderTaskPack({ conversations, taskExamples }) {
  const lines = [
    '<!-- Generated by eval/score/build-calibration-pack.js. Paste into task-fidelity.md. -->',
    '',
    '## Conversations',
    '',
  ];
  for (const [id, messages] of conversations) {
    lines.push(`### CONV-${id}`, '', '```', renderConversation(messages, []), '```', '');
  }

  lines.push('## Section 1 — Real output (you rate these)', '');
  taskExamples.forEach((ex, i) => {
    lines.push(
      `### R-${i + 1}`,
      `- Conversation: CONV-${ex.scenarioId} (run ${ex.runId})`,
      `- Cited as evidence: ${ex.cited.length ? ex.cited.join(', ') : 'none'}`,
      '- Extracted task:',
      `  - title: ${ex.title ?? '(none)'}`,
      `  - description: ${ex.description ?? '(none)'}`,
      `- Reference (one acceptable phrasing): ${ex.reference ?? '(none)'}`,
      ''
    );
  });

  lines.push('### Your ratings — Section 1', '', '| ID | Rating (1-4) | Reason (one line) |', '|---|---|---|');
  taskExamples.forEach((_, i) => lines.push(`| R-${i + 1} |  |  |`));
  lines.push('');
  return lines.join('\n');
}

function renderResponsePack({ conversations, responseExamples }) {
  const lines = [
    '<!-- Generated by eval/score/build-calibration-pack.js. Paste into response-quality.md. -->',
    '',
    '## Section 1 — Real output (you rate these)',
    '',
  ];

  responseExamples.forEach((ex, i) => {
    const messages = conversations.get(ex.scenarioId) ?? [];
    // Only what the agent could see when it answered — judging it against
    // later messages would penalise it for not seeing the future.
    const upTo = messages.filter((m) => m.number <= ex.questionNumber);
    lines.push(
      `### R-${i + 1}`,
      `- Scenario: ${ex.scenarioId} (run ${ex.runId}), question at message ${ex.questionNumber}`,
      '',
      '```',
      renderConversation(upTo, [ex.questionNumber]),
      '```',
      '',
      '- The reply:',
      '',
      '  > ' + (ex.reply ? ex.reply.replace(/\n/g, '\n  > ') : '**(no reply was sent)**'),
      '',
      '- Facts a correct answer needs to convey:',
      ...ex.points.map((p) => `  - ${p}`),
      ''
    );
  });

  lines.push('### Your ratings — Section 1', '', '| ID | Rating (1-4) | Reason (one line) |', '|---|---|---|');
  responseExamples.forEach((_, i) => lines.push(`| R-${i + 1} |  |  |`));
  lines.push('');
  return lines.join('\n');
}

function main() {
  const dirs = process.argv.slice(2);
  if (dirs.length === 0) {
    console.error('Usage: node eval/score/build-calibration-pack.js <bundle-dir>...');
    process.exit(1);
  }

  const collected = collect(dirs);
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const taskFile = path.join(OUT_DIR, 'task-fidelity.real.md');
  const respFile = path.join(OUT_DIR, 'response-quality.real.md');
  fs.writeFileSync(taskFile, renderTaskPack(collected));
  fs.writeFileSync(respFile, renderResponsePack(collected));

  const noReply = collected.responseExamples.filter((e) => !e.reply).length;
  console.log(`bundles read      : ${dirs.length}`);
  console.log(`task examples     : ${collected.taskExamples.length}  -> ${taskFile}`);
  console.log(`response examples : ${collected.responseExamples.length} (${noReply} with no reply) -> ${respFile}`);
  console.log('\nKeep ~8 task and ~6 response examples; prefer variety of wording over volume.');
}

if (require.main === module) main();

module.exports = { collect, renderConversation };
